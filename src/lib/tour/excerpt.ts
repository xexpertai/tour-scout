/**
 * The redacted request → result excerpt shown in the README and the Devpost text, generated from a
 * stored preset so its Q-ids, request parameters and numbers can never drift from the capture.
 * `npm run docs:excerpt` rewrites the marked blocks; a test fails if they are stale.
 */
import { SMALL_ROOM_POPULARITY } from "./pipeline.ts";
import type { Source } from "../evidence.ts";
import type { CapturedRun } from "./presets.ts";
import type { TourPlan } from "./types.ts";

const one = (v: number) => (Math.round(v * 1000) / 10).toFixed(1);
const short = (name: string) => name.replace(/, (ME|OR)$/, " $1").replace(/ Venue, Restaurant, Distillery$/, "");

function find(sources: Source[], test: (label: string) => boolean): Source {
  const s = sources.find((x) => test(x.label));
  if (!s) throw new Error("excerpt: a source the excerpt needs is missing from the preset");
  return s;
}
const q = (s: Source) => s.call.requests[0]?.query ?? {};

export function requestExcerpt(run: CapturedRun): string {
  const plan = (run.events.find((e) => (e.event as { type: string }).type === "plan")?.event as { plan: TourPlan }).plan;
  // Emerging-act mode signals with the "sounds like" artists, not the new act's own name.
  const act = plan.artist.proxyOf?.length ? plan.artist.proxyOf.join(", ") : plan.artist.name;
  const stops = [...plan.stops].sort((a, b) => a.order - b.order);
  const first = stops[0];
  const city = first.city.name;
  const src = plan.sources;
  const heat = find(src, (l) => l.includes("concentrate across"));
  const rooms = find(src, (l) => l.startsWith(`Rooms in ${city} `));
  const roomIds = src.filter((s) => s.label.startsWith("Rooms in ")).map((s) => Number(s.id.slice(1)));
  const cluster = find(src, (l) => l.includes(`concentrate in ${city}`));
  const openers = find(src, (l) => l.startsWith("Similar ") && l.endsWith(`in ${city}`));
  const overlap = find(src, (l) => l.startsWith("Audience overlap") && l.endsWith(first.opener?.name ?? "\u0000"));
  const cov = plan.coverage!;
  const hotspotCities = [...(plan.candidates ?? []).filter((c) => c.hotspot).map((c) => short(c.name)), ...cov.unscored];
  const pad = (id: string) => id.padEnd(5);
  const lines = [
    `${pad(heat.id)}where_popular   GET /v2/insights  filter.type=urn:heatmap, signal.interests.entities=<${act}>,`,
    `                                       filter.location.query=${q(heat)["filter.location.query"]}, take=${q(heat).take}`,
    `     → ${cov.hotspotCells} hotspot cells (~30 km each), near touring cities: ${hotspotCities.join(", ")}.`,
    `       ${cov.remoteCells} ${cov.remoteCells === 1 ? "cell" : "cells"} far from any touring city ${cov.remoteCells === 1 ? "is" : "are"} counted, not scheduled.`,
    "",
    `${pad(rooms.id)}recommend       GET /v2/insights  filter.type=urn:entity:place, signal.interests.entities=<${act}>,`,
    `                                       filter.location.query=${q(rooms)["filter.location.query"]},`,
    `                                       filter.tags=${[q(rooms)["filter.tags"]].flat().join(",")}, take=${q(rooms).take}`,
    `     → ${first.venues.map((v) => `${short(v.name)} ${one(v.affinity ?? 0)}`).join(" · ")}   ⇒ ${short(city)} room affinity ${one(first.city.affinity)}`,
    `       (rooms that are not venues, or more than 18 km out of town, are dropped first; ${cov.droppedRooms ?? 0} were in this run)`,
    "",
    `Q${Math.min(...roomIds)}–Q${Math.max(...roomIds)} (the same request for each candidate city)`,
    `     → ${(plan.candidates ?? []).map((c) => `${short(c.name)} ${one(c.affinity)}`).join(" · ")}`,
    `       ⇒ stops: the ${stops.length} best within a day's drive of each other, routed ${stops.map((s) => short(s.city.name)).join(" → ")}`,
    "",
    `${pad(cluster.id)}where_popular   GET /v2/insights  filter.type=urn:heatmap, filter.location.query=${q(cluster)["filter.location.query"]}, take=${q(cluster).take}`,
    `     → strongest cell named via OpenStreetMap: ${first.cluster?.name ?? "(no local name)"}`,
    "",
    `${pad(openers.id)}recommend       GET /v2/insights  filter.type=${q(openers)["filter.type"]}, signal.location.query=${q(openers)["signal.location.query"]}, take=${q(openers).take}`,
    `     → ${first.opener?.name} (first candidate that is not the act, not a member of it, and ${plan.artist.proxyOf?.length ? `within the support-slot size rule: Qloo popularity ≤ ${SMALL_ROOM_POPULARITY}` : "not more popular than the act"})`,
    "",
    `${pad(overlap.id)}compare_audiences GET /v2/analysis/compare  a=<${act}>, b=<${first.opener?.name}>`,
    `     → shared taste tags: ${first.opener?.overlap?.shared.join(", ")}`,
  ];
  return ["```text", ...lines, "```"].join("\n");
}

export const EXCERPT_START = "<!-- request-excerpt:start (generated by `npm run docs:excerpt` from public/presets/us-emerging.json) -->";
export const EXCERPT_END = "<!-- request-excerpt:end -->";

/** Replaces the marked block in a document with the excerpt. */
export function withExcerpt(doc: string, excerpt: string): string {
  const a = doc.indexOf(EXCERPT_START), b = doc.indexOf(EXCERPT_END);
  if (a < 0 || b < a) throw new Error("excerpt markers not found");
  return `${doc.slice(0, a)}${EXCERPT_START}\n${excerpt}\n${doc.slice(b)}`;
}
